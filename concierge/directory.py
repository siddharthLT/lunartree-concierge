"""Read-only lookup over the CDMO Live attendee directory.

The backing JSON is generated by scripts/build_cdmo_directory.py and holds PII,
so it is gitignored. If it's missing the welcome flow still works through the
"I'm not on the list" path.
"""
import json
import re
from functools import lru_cache
from pathlib import Path

DATA_PATH = Path(__file__).resolve().parent / 'data' / 'cdmo_live_directory.json'


@lru_cache(maxsize=1)
def _load():
    try:
        raw = json.loads(DATA_PATH.read_text())
    except (OSError, ValueError):
        return {'companies': {}, 'people': {}, 'index': []}
    people = {p['id']: p for p in raw['people']}
    index = [(p['id'], f"{p['name']} {raw['companies'][p['company']]['name']}".lower()) for p in raw['people']]
    return {'companies': raw['companies'], 'people': people, 'index': index}


def _company_for(person):
    return _load()['companies'][person['company']]


def search(query, limit=8):
    tokens = [t for t in re.split(r'\s+', query.lower().strip()) if t]
    if not tokens or sum(len(t) for t in tokens) < 2:
        return []
    data = _load()
    hits = []
    for pid, hay in data['index']:
        words = re.split(r'[^a-z0-9]+', hay)
        if all(any(w.startswith(t) for w in words) for t in tokens):
            p = data['people'][pid]
            hits.append({
                'id': pid, 'name': p['name'], 'title': p['title'],
                'company': _company_for(p)['name'],
                'rank': 0 if hay.startswith(tokens[0]) else 1,
            })
    hits.sort(key=lambda h: (h['rank'], h['name']))
    for h in hits:
        h.pop('rank')
    return hits[:limit]


def person_detail(pid):
    """Everything the chat needs after someone picks themselves."""
    p = _load()['people'].get(pid)
    if not p:
        return None
    c = _company_for(p)
    return {
        'id': p['id'], 'name': p['name'], 'title': p['title'],
        'company': {'name': c['name'], 'domain': c['domain']},
        'segment': c['segment'], 'modalities': c['modalities'],
        'email': p['email'],
    }


def person_email(pid):
    p = _load()['people'].get(pid)
    return p['email'] if p else ''


def norm(name):
    n = re.sub(r'[^a-z0-9 ]', ' ', (name or '').lower())
    n = re.sub(r'\b(inc|llc|ltd|limited|corp|corporation|co|company|gmbh|ag|sa|plc|group|pvt|private|the|lp|bv|nv|sas|spa|srl|usa|us)\b', ' ', n)
    return re.sub(r'\s+', ' ', n).strip()


def company_key(directory_id='', company_name=''):
    """Directory key for a visitor's company: via their directory person if
    they picked one, else by normalised name."""
    data = _load()
    p = data['people'].get(directory_id)
    if p:
        return p['company']
    k = norm(company_name)
    return k if k in data['companies'] else ''
